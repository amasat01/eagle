"""Writes reduce_order_expected.inc: the old device reduction (eagle seam ``reduce_canonical_device``, policy ordered) over the
order-exposing inputs of device_ops_test.c, as the raw bits of each column's sum.

usage: python reduce_order_oracle.py > reduce_order_expected.inc   (a GPU, cupy and the eagle binding)
The inputs must match ``order_input`` in device_ops_test.c: a splitmix64 hash of the flat index picks sign and a 24-bit
mantissa; even samples are scaled by 1e8, odd ones by 1.
"""
import cupy as cp
import numpy as np
from eagle import _core

SIZES = (1, 31, 32, 33, 1000, 65537, 1 << 20)
COLS = 2
SUM, DTYPES = 0, {32: (np.float32, np.uint32, 0), 64: (np.float64, np.uint64, 1)}


def order_input(n, dtype):
    """The (COLS, n) input: mixed magnitudes with random sign and mantissa."""
    k = np.arange(COLS * n, dtype=np.uint64)
    with np.errstate(over="ignore"):
        z = k * np.uint64(0x9E3779B97F4A7C15) + np.uint64(0x9E3779B97F4A7C15)
        z = (z ^ (z >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        z = (z ^ (z >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
    z ^= z >> np.uint64(31)
    mantissa = 1.0 + (z >> np.uint64(40)).astype(np.float64) / 16777216.0
    scale = np.where((k % np.uint64(n)) % np.uint64(2) == 0, 1e8, 1.0)
    return (np.where((z >> np.uint64(39)) & np.uint64(1), -1.0, 1.0) * mantissa * scale).reshape(COLS, n).astype(dtype)


print("/* Generated by reduce_order_oracle.py: do not edit. */")
print("struct order_row {\n    int bits;\n    int64_t n;\n    uint64_t sum[%d];\n};\n" % COLS)
print("static const struct order_row ORDER_ROWS[] = {")
for bits, (dtype, utype, code) in DTYPES.items():
    for n in SIZES:
        x = order_input(n, dtype)
        dx = cp.asarray(np.ascontiguousarray(x.T))    # the seam reads (rows, cols) row-major
        out = cp.zeros(COLS, dtype=dtype)
        work = int(_core.reduce_canonical_device(0, n, code, SUM, 0, 0, 0, 0, -1, 1, COLS))
        wa, wb = cp.zeros(work, dtype=dtype), cp.zeros(work, dtype=dtype)
        _core.reduce_canonical_device(dx.data.ptr, n, code, SUM, out.data.ptr, wa.data.ptr, wb.data.ptr, 0, -1, 1, COLS)
        cp.cuda.Device().synchronize()
        words = cp.asnumpy(out).view(utype).astype(np.uint64)
        print("    { %d, %d, { %s } }," % (bits, n, ", ".join("0x%016xULL" % int(w) for w in words)))
print("};")
