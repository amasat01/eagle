"""Regenerate the reproduction lock files from their ``.in`` specs.

Two kinds of lock live next to this script:

``toolchain-linux-64.lock``
    An explicit conda lock (``@EXPLICIT``, one URL + md5 per package) for the
    build toolchain shared by both profiles: Python, GCC 14, CMake, Ninja and
    the CUDA 12.9 compiler. Solved by ``micromamba create --dry-run --json``
    from ``toolchain.in``; nothing is installed.

``cards-gpu.txt`` / ``cards-cpu.txt``
    pip requirements with one ``--hash`` per package: the full transitive
    closure of ``cards-<profile>.in`` for CPython 3.12 on manylinux x86_64,
    resolved by ``pip install --dry-run --report``; nothing is installed.
    Install them with ``pip install --no-deps --require-hashes -r``.

Usage::

    python make_locks.py toolchain [--cuda 12|13] [--micromamba PATH]
    python make_locks.py pip gpu|cpu [--cuda 12|13] [--python PATH]

``--cuda 13`` (default 12) selects the CUDA 13 specs and writes the files with a
``-cuda13`` suffix: ``toolchain-cuda13.in`` -> ``toolchain-linux-64-cuda13.lock``,
``cards-gpu-cuda13.in`` -> ``cards-gpu-cuda13.txt``. There is no CPU profile for CUDA 13
(the CPU profile has no CUDA runtime).
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
PY_VERSION = "3.12"
# manylinux tags a glibc-2.28 x86_64 host accepts (the NCCL and PyTorch wheels
# use 2_18/2_28, so the whole range is listed rather than the 2014 alias alone).
PLATFORMS = [f"manylinux_2_{v}_x86_64" for v in range(17, 29)] + [
    "manylinux2014_x86_64", "linux_x86_64"]


def _spec_lines(path: pathlib.Path) -> list[str]:
    out = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def _header(path: pathlib.Path) -> list[str]:
    """The leading comment block of an ``.in`` file, copied into its lock."""
    out = []
    for line in path.read_text().splitlines():
        if not line.startswith("#"):
            break
        out.append(line)
    return out


def _suffix(cuda: str) -> str:
    return "-cuda13" if cuda == "13" else ""


def toolchain(micromamba: str, cuda: str = "12") -> None:
    sfx = _suffix(cuda)
    spec = HERE / f"toolchain{sfx}.in"
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [micromamba, "create", "--dry-run", "--json", "-y",
               "-r", str(pathlib.Path(tmp) / "root"), "-p", str(pathlib.Path(tmp) / "env"),
               "-c", "conda-forge", "--override-channels", *_spec_lines(spec)]
        env = dict(os.environ)
        if cuda == "13":  # cuda-version 13 requires the __cuda virtual package, absent on a machine with no GPU
            env.setdefault("CONDA_OVERRIDE_CUDA", "13.4")
        res = subprocess.run(cmd, check=True, capture_output=True, text=True, env=env)
    link = json.loads(res.stdout)["actions"]["LINK"]
    lines = _header(spec) + [
        f"# Generated by make_locks.py toolchain{' --cuda ' + cuda if sfx else ''} from {spec.name} ({len(link)} packages).",
        "@EXPLICIT"]
    lines += [f"{p['url']}#{p['md5']}" for p in sorted(link, key=lambda p: p["name"])]
    out = HERE / f"toolchain-linux-64{sfx}.lock"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(link)} packages)")


def _pypi_sha256(name: str, version: str, filename: str) -> str:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as r:
        meta = json.load(r)
    for f in meta["urls"]:
        if f["filename"] == filename:
            return f["digests"]["sha256"]
    raise SystemExit(f"no sha256 for {filename} on PyPI")


def pip_lock(profile: str, python: str, cuda: str = "12") -> None:
    sfx = _suffix(cuda)
    if sfx and profile != "gpu":
        raise SystemExit("--cuda 13 has a gpu profile only (the cpu profile has no CUDA runtime)")
    spec = HERE / f"cards-{profile}{sfx}.in"
    with tempfile.TemporaryDirectory() as tmp:
        report = pathlib.Path(tmp) / "report.json"
        cmd = [python, "-m", "pip", "install", "-q", "--dry-run", "--ignore-installed",
               "--report", str(report), "--only-binary=:all:", "--implementation", "cp",
               "--python-version", PY_VERSION, "--target", str(pathlib.Path(tmp) / "t")]
        for p in PLATFORMS:
            cmd += ["--platform", p]
        cmd += ["-r", str(spec)]
        subprocess.run(cmd, check=True)
        items = json.loads(report.read_text())["install"]
    index_lines = [ln for ln in _spec_lines(spec) if ln.startswith("--")]
    lines = _header(spec) + [
        f"# Generated by make_locks.py pip {profile}{' --cuda ' + cuda if sfx else ''} from {spec.name} "
        f"({len(items)} packages, CPython {PY_VERSION}, manylinux x86_64).",
        f"# Install: pip install --no-deps --require-hashes -r cards-{profile}{sfx}.txt",
        *index_lines]
    for it in sorted(items, key=lambda i: i["metadata"]["name"].lower()):
        name, version = it["metadata"]["name"], it["metadata"]["version"]
        url = it["download_info"]["url"]
        hashes = it["download_info"].get("archive_info", {}).get("hashes", {})
        sha = hashes.get("sha256") or _pypi_sha256(name, version, url.rsplit("/", 1)[1])
        lines.append(f"{name}=={version} \\\n    --hash=sha256:{sha}")
    out = HERE / f"cards-{profile}{sfx}.txt"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(items)} packages)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="what", required=True)
    t = sub.add_parser("toolchain")
    t.add_argument("--cuda", choices=["12", "13"], default="12")
    t.add_argument("--micromamba", default=shutil.which("micromamba") or "micromamba")
    p = sub.add_parser("pip")
    p.add_argument("profile", choices=["gpu", "cpu"])
    p.add_argument("--cuda", choices=["12", "13"], default="12")
    p.add_argument("--python", default=sys.executable)
    args = ap.parse_args(argv)
    if args.what == "toolchain":
        toolchain(args.micromamba, args.cuda)
    else:
        pip_lock(args.profile, args.python, args.cuda)
    return 0


if __name__ == "__main__":
    sys.exit(main())
